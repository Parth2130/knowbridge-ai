class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#718096"))
        
        # Header rule
        self.setStrokeColor(colors.HexColor("#DFE9F2"))
        self.setLineWidth(0.5)
        self.line(40, 750, 572, 750)
        self.drawString(40, 755, "KNOWBRIDGE AI — Enterprise Project Knowledge Handover Report")
        
        # Footer rule
        self.line(40, 45, 572, 45)
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(572, 32, page_text)
        self.drawString(40, 32, "Confidential — Generated by KnowBridge AI (Team Code Crushers)")
        self.restoreState()


class ReportGenerator:
    @staticmethod
    def compile_report_data(project_id, user_id=None):
        """
        Compiles the complete 16-section handover report dataset from the live database.
        """
        project = Project.query.get(project_id)
        if not project:
            raise ValueError(f"Project #{project_id} not found.")

        tasks = Task.query.filter_by(project_id=project_id).all()
        decisions = Decision.query.filter_by(project_id=project_id).all()
        risks = Risk.query.filter_by(project_id=project_id).all()
        dependencies = Dependency.query.filter_by(project_id=project_id).all()
        documents = Document.query.filter_by(project_id=project_id).all()

        completed_tasks = [t.to_dict() for t in tasks if t.status == 'Completed']
        pending_tasks = [t.to_dict() for t in tasks if t.status != 'Completed']

        # Task responsibilities
        responsibilities = {}
        for t in tasks:
            owner = t.responsible_person or 'Unassigned'
            if owner not in responsibilities:
                responsibilities[owner] = []
            responsibilities[owner].append({
                'task': t.description,
                'status': t.status,
                'deadline': t.deadline
            })

        # Deadlines list
        deadlines = []
        for t in tasks:
            if t.deadline and t.deadline not in ('Not specified', 'Pending scheduling'):
                deadlines.append({
                    'item': t.description,
                    'deadline': t.deadline,
                    'responsible': t.responsible_person,
                    'status': t.status
                })

        # Supporting evidence compilation
        evidence_items = []
        for t in tasks:
            ev = Evidence.query.filter_by(entity_type='task', entity_id=t.id).first()
            if ev:
                evidence_items.append({
                    'item_type': 'Task',
                    'item_name': t.description,
                    'document_name': ev.document.original_filename if ev.document else 'Project Doc',
                    'page_number': ev.page_number,
                    'quote': ev.original_text
                })
        for d in decisions:
            ev = Evidence.query.filter_by(entity_type='decision', entity_id=d.id).first()
            if ev:
                evidence_items.append({
                    'item_type': 'Decision',
                    'item_name': d.title,
                    'document_name': ev.document.original_filename if ev.document else 'Project Doc',
                    'page_number': ev.page_number,
                    'quote': ev.original_text
                })

        # Missing information
        missing_info = []
        unassigned_count = len([t for t in tasks if t.responsible_person == 'Unassigned'])
        if unassigned_count:
            missing_info.append(f"{unassigned_count} identified tasks require assignment to team members.")
        if not deadlines:
            missing_info.append("Milestone completion target dates have not been scheduled.")
        if not risks:
            missing_info.append("Operational disaster recovery and backup runbooks need verification.")

        # Next Action Plan (30-60-90 Day Plan)
        action_plan = [
            {"timeframe": "First 7 Days", "action": f"Incoming lead {project.incoming_member} reviews code repositories, architectural decisions, and schedules initial Q&A with {project.outgoing_member}."},
            {"timeframe": "First 30 Days", "action": "Assume complete primary ownership of active sprints, verify deployment permissions, and resolve high-priority pending items."},
            {"timeframe": "First 60 Days", "action": "Review long-term technical dependencies and address remaining architectural risks and documentation debt."}
        ]

        # Latest approval status
        latest_approval = Approval.query.filter_by(entity_type='report', entity_id=project_id).order_by(Approval.created_at.desc()).first()
        approval_status = {
            'status': 'Approved' if latest_approval and latest_approval.action == 'Approve' else 'Pending Review',
            'reviewer': latest_approval.reviewer_name if latest_approval else 'Pending Reviewer Assignment',
            'comments': latest_approval.comments if latest_approval else 'Awaiting final verification review.'
        }

        report_dict = {
            '1_project_title': project.name,
            '2_project_description': project.description or 'No project description provided.',
            '3_outgoing_member': project.outgoing_member,
            '4_incoming_member': project.incoming_member,
            '5_project_summary': f"Official knowledge handover for {project.name} in category '{project.category}'. Generated automatically by KnowBridge AI platform.",
            '6_completed_tasks': completed_tasks,
            '7_pending_tasks': pending_tasks,
            '8_important_decisions': [d.to_dict() for d in decisions],
            '9_task_responsibilities': responsibilities,
            '10_deadlines': deadlines,
            '11_identified_risks': [r.to_dict() for r in risks],
            '12_dependencies': [dp.to_dict() for dp in dependencies],
            '13_supporting_evidence': evidence_items,
            '14_missing_information': missing_info,
            '15_next_action_plan': action_plan,
            '16_approval_status': approval_status,
            'category': project.category,
            'start_date': project.start_date,
            'deadline': project.deadline,
            'document_count': len(documents),
            'generated_at': datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')
        }

        return report_dict

